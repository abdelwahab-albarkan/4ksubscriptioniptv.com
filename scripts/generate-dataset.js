// Fill cross-linking silos (attach 8 related slugs for internal linking to every page)
for (let i = 0; i < allPages.length; i++) {
  const currentPage = allPages[i];
  const sameCategory = allPages.filter(p => p.category === currentPage.category && p.slug !== currentPage.slug);
  const otherCategory = allPages.filter(p => p.category !== currentPage.category);

  // Pick 4 from same category + 4 from other category
  const relatedSame = sameCategory.slice(i % Math.max(1, sameCategory.length - 4), (i % Math.max(1, sameCategory.length - 4)) + 4);
  const relatedOther = otherCategory.slice((i * 2) % Math.max(1, otherCategory.length - 4), ((i * 2) % Math.max(1, otherCategory.length - 4)) + 4);

  currentPage.relatedPages = [...relatedSame, ...relatedOther].map(p => ({
    slug: p.slug,
    title: p.title,
    h1: p.h1,
    country: p.country
  }));
}

